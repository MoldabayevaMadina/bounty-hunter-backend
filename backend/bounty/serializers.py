from rest_framework import serializers

from .models import HuntLog, WantedCriminal


class WantedCriminalSerializer(serializers.ModelSerializer):
    last_known_location = serializers.SerializerMethodField()
    hunt_count = serializers.SerializerMethodField()

    class Meta:
        model = WantedCriminal
        fields = ["id", "name", "nickname", "reward", "last_known_location", "difficulty",
                  "armed", "has_crew", "escape_master", "hunt_count"]

    def get_last_known_location(self, obj):
        return {
            "latitude": obj.last_known_latitude,
            "longitude": obj.last_known_longitude,
            "note": obj.last_known_note,
        }

    def get_hunt_count(self, obj):
        return obj.hunt_logs.count()


class HuntLogSerializer(serializers.ModelSerializer):
    # Client sends "criminal_id"; DRF checks that this criminal exists (otherwise 400).
    criminal_id = serializers.PrimaryKeyRelatedField(source="criminal", queryset=WantedCriminal.objects.all())
    criminal_nickname = serializers.CharField(source="criminal.nickname", read_only=True)

    class Meta:
        model = HuntLog
        fields = ["id", "criminal_id", "criminal_nickname", "success", "notes", "created_at"]
        read_only_fields = ["created_at"]          # timestamp is generated by the server
        extra_kwargs = {"success": {"required": True}}

    def validate_criminal_id(self, value):
        # A journal entry can't be moved to another criminal after it is created.
        if self.instance and value != self.instance.criminal:
            raise serializers.ValidationError("criminal_id can't be changed; create a new log instead.")
        return value